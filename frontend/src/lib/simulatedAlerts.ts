/**
 * Dynamically produces 20 simulated collision alerts with dates
 * strictly between 7.0 and 14.0 days into the future.
 */
export function generateSimulatedAlerts(): ConjunctionAlert[] {
  const now = Date.now();
  const createdDate = new Date(now - 3600_000 * 2).toISOString();

  return BASE_SIMULATED_DATA.map((item) => {
    const tcaTimestamp = now + item.daysOffset * 86_400_000;
    const tcaIso = new Date(tcaTimestamp).toISOString();

    return {
      id: item.id,
      primarySatellite: item.primarySatellite,
      primaryNoradId: item.primaryNoradId,
      secondaryObject: item.secondaryObject,
      secondaryNoradId: item.secondaryNoradId,
      tca: tcaIso,
      missDistanceKm: item.missDistanceKm,
      missDistanceM: item.missDistanceKm * 1000.0,
      relativeVelocityKmS: item.relativeVelocityKmS,
      probability: item.probability,
      riskLevel: item.riskLevel,
      status: item.status,
      screeningScope: item.screeningScope,
      detectedBy: "satguard_simulated",
      createdAt: createdDate,
      computedAt: createdDate,
    };
  });
}

export function calculateAverageAltitudeKm(satellites: Satellite[]): number {
  if (satellites.length === 0) return 0;
  const total = satellites.reduce((sum, sat) => sum + sat.altitudeKm, 0);
  return Math.round(total / satellites.length);
}

